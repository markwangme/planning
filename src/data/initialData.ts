export function getCleaningDuration(fromFormula: FormulaType | null, toFormula: FormulaType): { duration: number; reason: string } {
  if (!fromFormula) return { duration: 0, reason: "初次开机免洗" };
  const rule = CLEANING_RULES.find((r) => r.from === fromFormula && r.to === toFormula);
  if (rule) {
    return { duration: rule.durationHours, reason: rule.description };
  }
  // 默认跨配方清洗
  return { duration: 2.5, reason: "标准溶剂冲洗与吹扫" };
}

